"""MariaDB → PostgreSQL 신규 테이블 복사. 원본 읽기 전용, 대상 전체 트랜잭션."""

import argparse
from collections import Counter
from datetime import date, datetime
from decimal import Decimal
import gzip
import hashlib
import json
from pathlib import Path
import re

from cv_store.config.settings import PROJECT_ROOT, db_engine
from cv_store.database.connection import connection, open_cursor, source_connection
from cv_store.database.inspect import inspect_source


def quote_identifier(value):
    return '"' + value.replace('"', '""') + '"'


def source_identifier(value):
    return "`" + value.replace("`", "``") + "`"


def postgres_type(column):
    kind = column["data_type"].lower()
    unsigned = "unsigned" in column["column_type"].lower()
    if kind in {"tinyint", "smallint"}:
        return "INTEGER" if unsigned else "SMALLINT"
    if kind in {"mediumint", "int", "integer"}:
        return "BIGINT" if unsigned else "INTEGER"
    if kind == "bigint":
        return "NUMERIC(20, 0)" if unsigned else "BIGINT"
    if kind in {"float", "double"}:
        # 원본 클라이언트가 읽은 부동소수 값을 그대로 보존하기 위해 승격합니다.
        return "DOUBLE PRECISION"
    if kind in {"decimal", "numeric"}:
        return f"NUMERIC({int(column['numeric_precision'])}, {int(column['numeric_scale'])})"
    if kind in {"char", "varchar"}:
        return f"VARCHAR({int(column['max_length'])})"
    if kind in {"tinytext", "text", "mediumtext", "longtext"}:
        return "TEXT"
    if kind in {"datetime", "timestamp"}:
        return "TIMESTAMP WITHOUT TIME ZONE"
    if kind == "date":
        return "DATE"
    raise ValueError(f"자동 변환하지 않는 자료형: {kind}")


def default_sql(value):
    if value is None or str(value).upper() == "NULL":
        return ""
    text = str(value)
    if re.fullmatch(r"[+-]?\d+(?:\.\d+)?", text):
        return " DEFAULT " + text
    if text.startswith("'") and text.endswith("'"):
        literal = text[1:-1].replace("''", "'")
        return " DEFAULT '" + literal.replace("'", "''") + "'"
    if text.upper() in {"CURRENT_TIMESTAMP", "CURRENT_TIMESTAMP()"}:
        return " DEFAULT CURRENT_TIMESTAMP"
    raise ValueError("알 수 없는 기본값 식은 수동 변환이 필요합니다.")


def create_table_sql(table):
    fields = []
    names = [c["name"].lower() for c in table["columns"]]
    if len(set(names)) != len(names):
        raise ValueError("소문자 변환 후 컬럼 이름이 충돌합니다.")
    for column in table["columns"]:
        if column.get("generation_expression"):
            raise ValueError("생성 컬럼은 수동 변환이 필요합니다.")
        field = quote_identifier(column["name"].lower()) + " " + postgres_type(column)
        if "auto_increment" in column.get("extra", ""):
            if postgres_type(column) not in {"SMALLINT", "INTEGER", "BIGINT"}:
                raise ValueError("자동 증가 키를 정수 identity로 변환할 수 없습니다.")
            field += " GENERATED BY DEFAULT AS IDENTITY"
        else:
            field += default_sql(column.get("default_value"))
        if column["nullable"] == "NO":
            field += " NOT NULL"
        fields.append(field)
    primary = sorted((i for i in table["indexes"] if i["name"] == "PRIMARY"), key=lambda i: i["position"])
    if primary:
        fields.append("PRIMARY KEY (" + ", ".join(quote_identifier(i["column_name"].lower()) for i in primary) + ")")
    return "CREATE TABLE public." + quote_identifier(table["name"].lower()) + " (\n  " + ",\n  ".join(fields) + "\n)"


def copy_text(value):
    if value is None:
        return r"\N"
    if isinstance(value, datetime):
        value = value.isoformat(sep=" ", timespec="microseconds")
    elif isinstance(value, date):
        value = value.isoformat()
    text = str(value)
    if "\x00" in text:
        raise ValueError("PostgreSQL TEXT에 저장할 수 없는 NUL 문자가 있습니다.")
    return text.replace("\\", "\\\\").replace("\t", "\\t").replace("\n", "\\n").replace("\r", "\\r")


def canonical_value(value):
    if value is None:
        return None
    if isinstance(value, datetime):
        return ["datetime", value.isoformat(timespec="microseconds")]
    if isinstance(value, date):
        return ["date", value.isoformat()]
    if isinstance(value, (int, Decimal)):
        text = format(value, "f") if isinstance(value, Decimal) else str(value)
        if "." in text:
            text = text.rstrip("0").rstrip(".")
        return ["number", text]
    if isinstance(value, float):
        return ["float", value.hex()]
    return ["string", value]


def row_digest(row):
    payload = json.dumps([canonical_value(value) for value in row], ensure_ascii=False, separators=(",", ":"))
    return hashlib.sha256(payload.encode("utf-8")).digest()


def _copy_table(source, target_cursor, table, backup_dir):
    names = [c["name"] for c in table["columns"]]
    source_sql = "SELECT " + ", ".join(source_identifier(n) for n in names) + " FROM " + source_identifier(table["name"])
    target_name = "public." + quote_identifier(table["name"].lower())
    target_columns = ", ".join(quote_identifier(n.lower()) for n in names)
    source_hashes = Counter()
    count = 0
    # 실제 행은 Git 제외 대상인 runtime/ 압축 백업에만 저장합니다.
    with source.cursor() as cursor, gzip.open(backup_dir / (table["name"] + ".jsonl.gz"), "wt", encoding="utf-8") as backup:
        cursor.execute(source_sql)

        def blocks():
            nonlocal count
            while True:
                batch = cursor.fetchmany(1000)
                if not batch:
                    break
                lines = []
                for row in batch:
                    source_hashes[row_digest(row)] += 1
                    backup.write(json.dumps(list(row), ensure_ascii=False, default=str) + "\n")
                    lines.append("\t".join(copy_text(v) for v in row) + "\n")
                count += len(batch)
                yield "".join(lines).encode("utf-8")

        target_cursor.execute(f"COPY {target_name} ({target_columns}) FROM STDIN WITH (FORMAT text)", stream=blocks())
    target_cursor.execute(f"SELECT {target_columns} FROM {target_name}")
    copied = target_cursor.fetchall()
    if len(copied) != count or Counter(row_digest(row) for row in copied) != source_hashes:
        raise ValueError(f"원본과 복사본의 행 값이 다릅니다: {table['name']}")
    for col in table["columns"]:
        if "auto_increment" in col.get("extra", ""):
            name = col["name"].lower()
            target_cursor.execute(
                f"SELECT setval(pg_get_serial_sequence(%s, %s), "
                f"COALESCE((SELECT MAX({quote_identifier(name)}) FROM {target_name}), 1), "
                f"EXISTS(SELECT 1 FROM {target_name}))",
                ("public." + table["name"].lower(), name),
            )
    return {"table": table["name"], "source_rows": count, "target_rows": len(copied), "row_hash_match": True}


def migrate(report):
    if db_engine() != "postgresql":
        raise ValueError("대상은 PostgreSQL이어야 합니다.")
    if report.get("triggers") or report.get("views") or report.get("foreign_keys"):
        raise ValueError("트리거·뷰·외래 키는 별도 변환이 필요합니다.")
    for table in report["tables"]:
        if table["type"] != "BASE TABLE" or table["engine"] != "InnoDB":
            raise ValueError("일관된 스냅샷으로 복사할 수 없는 테이블이 있습니다.")
        create_table_sql(table)  # 쓰기 전에 모든 자료형을 검증합니다.
    stamp = datetime.now().strftime("%Y%m%d_%H%M%S")
    backup_dir = PROJECT_ROOT / "runtime" / "migration" / ("backup_" + stamp)
    backup_dir.mkdir(parents=True, exist_ok=False)
    (backup_dir / "source_schema.json").write_text(json.dumps(report, ensure_ascii=False, indent=2, default=str), encoding="utf-8")
    results = []
    with source_connection() as source, connection() as target:
        try:
            with open_cursor(target) as cursor:
                cursor.execute("SELECT pg_try_advisory_xact_lock(%s)", (69002171,))
                if not cursor.fetchone()[0]:
                    raise ValueError("다른 이전 프로세스가 실행 중입니다.")
                cursor.execute("SELECT table_name FROM information_schema.tables WHERE table_schema = 'public'")
                if cursor.fetchall():
                    raise ValueError("대상 public 스키마가 비어 있지 않습니다. 덮어쓰지 않습니다.")
                for table in report["tables"]:
                    cursor.execute(create_table_sql(table))
                    result = _copy_table(source, cursor, table, backup_dir)
                    results.append(result)
                    print(f"검증 완료: {result['table']} {result['target_rows']}행", flush=True)
                    groups = {}
                    for index in table["indexes"]:
                        if index["name"] != "PRIMARY":
                            groups.setdefault(index["name"], []).append(index)
                    for name, entries in groups.items():
                        entries.sort(key=lambda i: i["position"])
                        columns = ", ".join(quote_identifier(i["column_name"].lower()) for i in entries)
                        unique = "UNIQUE " if not entries[0]["non_unique"] else ""
                        cursor.execute(f"CREATE {unique}INDEX {quote_identifier(table['name'].lower() + '_' + name.lower())} "
                                       f"ON public.{quote_identifier(table['name'].lower())} ({columns})")
                for name, column in (("all_sale", "sale_date"), ("news_search", "news_date"), ("ytb_video", "published_at")):
                    if any(t["name"] == name for t in report["tables"]):
                        cursor.execute(f"CREATE INDEX {quote_identifier(name + '_date_store_idx')} ON public.{quote_identifier(name)} "
                                       f"({quote_identifier(column)}, lower(store_type))")
            target.commit()
        except Exception:
            target.rollback()
            raise
    output = {"verified_at": datetime.now().isoformat(), "target_committed": True, "tables": results}
    (backup_dir / "verification.json").write_text(json.dumps(output, ensure_ascii=False, indent=2), encoding="utf-8")
    return output


def main():
    parser = argparse.ArgumentParser(description="MariaDB → PostgreSQL. 기본은 스키마 변환 점검, --write로 실제 복사.")
    parser.add_argument("--write", action="store_true")
    args = parser.parse_args()
    try:
        report = inspect_source()
        for table in report["tables"]:
            create_table_sql(table)
        print(f"스키마 변환 검증: {len(report['tables'])}개 테이블")
        if args.write:
            result = migrate(report)
            print(f"이전 완료: {len(result['tables'])}개 테이블, 원본 변경 없음.")
        else:
            print("미리보기만 수행했습니다. 대상 쓰기 없음.")
    except Exception as exc:
        # 접속 정보나 실제 행이 포함될 수 있는 드라이버 오류 원문은 출력하지 않습니다.
        print(f"이전 중단 ({type(exc).__name__}). 대상 트랜잭션은 커밋하지 않았습니다.")
        raise SystemExit(1) from None


if __name__ == "__main__":
    main()
