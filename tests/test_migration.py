from datetime import datetime
from decimal import Decimal

import pytest

from cv_store.database.migrate import copy_text, create_table_sql, default_sql, postgres_type, quote_identifier, row_digest


def test_identifier_and_default_are_escaped():
    assert quote_identifier('1+1_"count') == '"1+1_""count"'
    assert default_sql("'KR'") == " DEFAULT 'KR'"
    assert default_sql("NULL") == ""
    assert default_sql("''") == " DEFAULT ''"
    with pytest.raises(ValueError):
        default_sql("untrusted_function()")


def test_unsigned_bigint_keeps_full_range():
    assert postgres_type({"data_type": "bigint", "column_type": "bigint unsigned"}) == "NUMERIC(20, 0)"


def test_copy_text_null_and_empty_and_backslash_are_distinct():
    assert copy_text(None) == r"\N"
    assert copy_text("") == ""
    assert copy_text(r"\N") == r"\\N"
    assert copy_text("a\tb\nc\r") == r"a\tb\nc\r"
    with pytest.raises(ValueError):
        copy_text("\x00")


def test_hash_preserves_values_and_numeric_promotions():
    assert row_digest([1, None]) == row_digest([Decimal("1"), None])
    assert row_digest([1, None]) != row_digest([1, ""])
    assert row_digest([datetime(2024, 1, 1)]) != row_digest(["2024-01-01"])
    assert row_digest([0.1]) != row_digest([0.100001])


def test_schema_preserves_identity_key_and_quoted_event_column():
    columns = [
        dict(name="ID", data_type="int", column_type="int(11)", extra="auto_increment", nullable="NO"),
        dict(name="1+1_event_count", data_type="int", column_type="int(11)", extra="", nullable="YES", default_value="NULL"),
    ]
    table = dict(name="all_sale", columns=columns, indexes=[dict(name="PRIMARY", column_name="ID", position=1)])
    sql = create_table_sql(table)
    assert '"id" INTEGER GENERATED BY DEFAULT AS IDENTITY NOT NULL' in sql
    assert '"1+1_event_count" INTEGER' in sql
    assert 'PRIMARY KEY ("id")' in sql


def test_unknown_type_stops_before_writes():
    with pytest.raises(ValueError):
        postgres_type({"data_type": "geometry", "column_type": "geometry"})
